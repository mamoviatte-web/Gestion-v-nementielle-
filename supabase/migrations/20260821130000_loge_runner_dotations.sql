-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.loge_dotations (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  space_id      UUID NOT NULL REFERENCES public.spaces(space_id) ON DELETE CASCADE,
  loge_label    TEXT NOT NULL,
  loge_sort     INT DEFAULT 0,
  product_id    UUID REFERENCES public.products(product_id),   -- NULL = générique/matériel
  product_label TEXT NOT NULL,
  qty           INT NOT NULL DEFAULT 0,
  UNIQUE (space_id, loge_label, product_label)
);
ALTER TABLE public.loge_dotations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS loge_dotations_stade ON public.loge_dotations;
CREATE POLICY loge_dotations_stade ON public.loge_dotations
  FOR ALL USING (public.is_stade()) WITH CHECK (public.is_stade());

