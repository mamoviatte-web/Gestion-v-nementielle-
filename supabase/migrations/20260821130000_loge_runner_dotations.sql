-- ─────────────────────────────────────────────────────────────────────────────
-- get_loge_runner_sheet — fiche runner d'un espace loge :
--   • detail par loge (dotation individuelle)
--   • synthèse par produit : total (Σ loges) − en_office (area_stocks) = à monter
-- ─────────────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.get_loge_runner_sheet(p_space uuid)
RETURNS json LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $fn$
  WITH syn AS (
    SELECT coalesce(ld.product_id::text, ld.product_label) AS key,
           min(ld.product_label) AS product_label,
           max(ld.product_id::text) AS product_id,
           sum(ld.qty) AS total,
           coalesce(max(a.current_qty), 0) AS en_office
    FROM public.loge_dotations ld
    LEFT JOIN public.area_stocks a ON a.area_id = ld.space_id AND a.product_id = ld.product_id
    WHERE ld.space_id = p_space
    GROUP BY coalesce(ld.product_id::text, ld.product_label)
  )
  SELECT json_build_object(
    'space_id', p_space,
    'space_name', (SELECT space_name FROM public.spaces WHERE space_id = p_space),
    'nb_loges', (SELECT count(DISTINCT loge_label) FROM public.loge_dotations WHERE space_id = p_space),
    'loges', (SELECT coalesce(json_agg(json_build_object('loge', loge_label, 'lignes', lignes) ORDER BY loge_sort, loge_label), '[]'::json)
              FROM (SELECT loge_label, min(loge_sort) loge_sort,
                      json_agg(json_build_object('produit', product_label, 'qte', qty) ORDER BY product_label) lignes
                    FROM public.loge_dotations WHERE space_id = p_space GROUP BY loge_label) x),
    'synthese', (SELECT coalesce(json_agg(json_build_object(
                    'produit', product_label, 'product_id', product_id,
                    'total', total, 'en_office', en_office,
                    'a_monter', greatest(total - en_office, 0)) ORDER BY product_label), '[]'::json) FROM syn)
  );
$fn$;
GRANT EXECUTE ON FUNCTION public.get_loge_runner_sheet(uuid) TO authenticated, anon;
