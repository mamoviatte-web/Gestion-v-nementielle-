-- Fiches runner LOGES — méthodo « dotation par loge individuelle + stockage ».
--
-- Chaque loge individuelle (Loge Est : Loges 2→16 ; Loge Ouest Nord = PAGNOL 1→4 ;
-- Loge Ouest Sud = GALICE 1→4) reçoit une dotation FIXE (référence importée du
